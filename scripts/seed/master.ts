export const NOW = toMs(FIXTURE_NOW)
export const daysAgo = (d: number, hour = 10, minute = 0) => {
  const base = NOW - d * DAY
  const date = new Date(base + 7 * 3_600_000)
  return Date.UTC(date.getUTCFullYear(), date.getUTCMonth(), date.getUTCDate(), hour, minute) - 7 * 3_600_000
}
export const isoDaysAgo = (d: number, hour = 10, minute = 0) => toIso(daysAgo(d, hour, minute))

