export function buildSellers(featured: (tenantId: string, index: number) => string[]): Seller[] {
  return sellerSeeds.map(({ joinedDaysAgo, templateId, allowed, ...s }, i) => ({
    ...s,
    templateId: templateId ?? 'tpl-personal-store',
    allowedTemplateIds: allowed ?? ['tpl-personal-store', 'tpl-sales-pro'],
    featuredProductIds: featured(s.tenantId, i),
    joinedAt: isoDaysAgo(joinedDaysAgo),
  }))
}

